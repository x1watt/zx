// Generates native/sfx/decoder/zc_dict_words.c, the word list of the
// self-extracting decoder: english.dic (the words of zcm_dict_words.dart)
// as a raw LZMA stream (LzmaEnc of the LZMA SDK port, the smallest of the
// lc settings), which the decoder unpacks with LzmaDecode: a few
// milliseconds even when interpreted, where zcm would take seconds.
//
//   dart run tool/zcm_gen_sfx_dict.dart [out.c]
//
// (default: native/sfx/decoder/zc_dict_words.c; "-" prints the size only).

import 'dart:io';
import 'dart:typed_data';

import 'package:zx/src/codec/lzma/lzma_enc.dart';
import 'package:zx/src/codec/zcm/zcm_dict_words.dart';

void main(List<String> a) {
  final path = a.isNotEmpty ? a[0] : 'native/sfx/decoder/zc_dict_words.c';
  final raw = Uint8List.fromList(zcmDictBytes());
  ({Uint8List props, Uint8List data})? best;
  for (var lc = 0; lc <= 4; lc++) {
    final p = LzmaEncProps()
      ..level = 9
      ..dictSize = 1 << 20
      ..lc = lc
      ..lp = 0
      ..pb = 0
      ..fb = 273;
    final r = lzmaEncode(raw, p);
    if (best == null || r.data.length < best.data.length) best = r;
  }
  final out = best!.data;
  stderr.writeln('raw ${raw.length} packed ${out.length}');
  if (path == '-') return;
  String list(Uint8List b) {
    final sb = StringBuffer();
    for (var i = 0; i < b.length; i += 16) {
      final e = i + 16 < b.length ? i + 16 : b.length;
      sb.writeln('  ${b.sublist(i, e).join(', ')},');
    }
    return sb.toString();
  }

  File(path).writeAsStringSync(
      '''// zxsfx decoder: the word list of the dictionary transform (zc_dict.c).
//
// english.dic of cmix (Byron Knoll): 44,515 English words in lowercase,
// most frequent first, one per line (zcm_dict_words.dart), as a raw LZMA
// stream. Generated by tool/zcm_gen_sfx_dict.dart; do not edit.

#include "zc_dict.h"

const i64 zdictWordsRawLen = ${raw.length};
const u8 zdictWordsProps[5] = {${best.props.join(', ')}};
const i64 zdictWordsLen = ${out.length};
const u8 zdictWords[${out.length}] = {
${list(out)}};
''');
}
