// Writes lib/src/format/zx/zx_sfx_payload.dart from the files built by
// tool/build_sfx.sh: the engines (engine-<arch>) and the decoder
// (zxsfx.wasm), as base64 text.
//
//   dart run tool/gen_sfx_payload.dart <out folder> <dart file>

import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final dir = args[0];
  final out = StringBuffer()
    ..writeln('// Generated by tool/build_sfx.sh (tool/gen_sfx_payload.dart) '
        'from native/sfx:')
    ..writeln('// the engines and the decoder of the self-extracting .zx '
        'archives (zx_sfx.dart).')
    ..writeln('// Do not edit.')
    ..writeln()
    ..writeln("import 'dart:convert';")
    ..writeln("import 'dart:typed_data';")
    ..writeln()
    ..writeln('/// The engine for [arch] (a name of zxSfxArches), or null.')
    ..writeln('Uint8List? zxSfxEngine(String arch) => switch (arch) {');
  final arches = ['x86_64', 'aarch64', 'riscv64', 'arm'];
  for (var i = 0; i < arches.length; i++) {
    out.writeln("      '${arches[i]}' => base64Decode(_engine$i),");
  }
  out
    ..writeln('      _ => null,')
    ..writeln('    };')
    ..writeln()
    ..writeln('/// The decoder (WebAssembly).')
    ..writeln('Uint8List zxSfxDecoder() => base64Decode(_decoder);')
    ..writeln();
  void blob(String name, String path) {
    final b64 = base64Encode(File(path).readAsBytesSync());
    out.writeln('const String $name =');
    for (var i = 0; i < b64.length; i += 76) {
      final end = i + 76 < b64.length ? i + 76 : b64.length;
      out.write("    '${b64.substring(i, end)}'");
      out.writeln(end == b64.length ? ';' : '');
    }
    out.writeln();
  }

  for (var i = 0; i < arches.length; i++) {
    blob('_engine$i', '$dir/engine-${arches[i]}');
  }
  blob('_decoder', '$dir/zxsfx.wasm');
  File(args[1]).writeAsStringSync(out.toString());
}
